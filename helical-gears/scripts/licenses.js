import { readdir, readFile, rename, rm } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";

const pluginDirectory = resolve(import.meta.dir, "..");
const output = process.argv[2] ?? join(pluginDirectory, "THIRD-PARTY-LICENSES.txt");
const separator = "\n\n------------------------------------------------------------------------\n\n";
const metadata = await Bun.$`cargo metadata --format-version 1 --locked --filter-platform wasm32-unknown-unknown`
  .cwd(pluginDirectory)
  .quiet()
  .json();

function wasmDependencies({ packages, resolve }) {
  const packagesById = new Map(packages.map((pkg) => [pkg.id, pkg]));
  const nodesById = new Map(resolve.nodes.map((node) => [node.id, node]));
  const visited = new Set([resolve.root]);
  const pending = [resolve.root];
  const dependencies = [];

  while (pending.length > 0) {
    const id = pending.pop();
    for (const dependency of nodesById.get(id).deps) {
      if (visited.has(dependency.pkg) || !dependency.dep_kinds.some(({ kind }) => kind === null)) {
        continue;
      }
      visited.add(dependency.pkg);
      const pkg = packagesById.get(dependency.pkg);
      // Proc macros run on the build host and their dependency trees stay there.
      if (pkg.targets.some(({ kind }) => kind.includes("proc-macro"))) {
        continue;
      }
      pending.push(pkg.id);
      dependencies.push(pkg);
    }
  }

  return dependencies.sort((a, b) =>
    a.name.localeCompare(b.name, "en") || a.version.localeCompare(b.version, "en"));
}

async function noticeFiles(pkg) {
  const directory = dirname(pkg.manifest_path);
  const entries = await readdir(directory, { withFileTypes: true });
  const files = new Set(entries
    .filter((entry) => (entry.isFile() || entry.isSymbolicLink()) &&
      /^(licen[cs]e|copying|notice|unlicense|copyright)/i.test(entry.name))
    .map((entry) => join(directory, entry.name)));
  if (pkg.license_file) {
    files.add(resolve(directory, pkg.license_file));
  }
  if (files.size === 0) {
    throw new Error(`Missing packaged license files for ${pkg.name} ${pkg.version}`);
  }

  return [...files].sort().map((path) => [relative(directory, path), path]);
}

const dependencies = wasmDependencies(metadata);
const sourceNotices = await readFile(join(pluginDirectory, "packaging", "source-notices.txt"), "utf8");
const licenseTexts = new Map();
for (const pkg of dependencies) {
  for (const [file, path] of await noticeFiles(pkg)) {
    const text = (await readFile(path, "utf8")).replaceAll("\r\n", "\n").trimEnd();
    const sources = licenseTexts.get(text) ?? [];
    sources.push(`${pkg.name} ${pkg.version} (${file})`);
    licenseTexts.set(text, sources);
  }
}

const inventory = dependencies
  .map((pkg) => `${pkg.name} ${pkg.version} (${pkg.license ?? "see license file"})`)
  .join("\n");
const notices = [...licenseTexts].map(([text, sources]) => `${sources.join("\n")}\n\n${text}`);
const header = [
  "Third-party software in Helical Gears",
  "Generated by `mise run licenses:helical-gears` from Cargo.lock and the crates' own license files.",
  "Rust standard library notices are in RUST-STDLIB-LICENSES.html in the plugin ZIP.",
  `Wasm dependencies\n${inventory}`,
].join("\n\n");
const contents = [header, sourceNotices.replaceAll("\r\n", "\n").trimEnd(), ...notices].join(separator);

const temporary = `${output}.${crypto.randomUUID()}.tmp`;
try {
  await Bun.write(temporary, `${contents}\n`);
  await rename(temporary, output);
} finally {
  await rm(temporary, { force: true });
}
